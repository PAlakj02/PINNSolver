    def __init__(self, num_layers=8, num_neurons=256, activation='tanh', dropout_rate=0.1, regularizer=tf.keras.regularizers.l2(1e-5), **kwargs):
        super(PINN, self).__init__(**kwargs)
        self.hidden_layers = [
            tf.keras.layers.Dense(
                num_neurons,
                activation=activation,
                kernel_regularizer=regularizer
            )
            for _ in range(num_layers)
        ]
        self.output_layer = tf.keras.layers.Dense(2)  # Real and Imaginary parts
        self.dropout = tf.keras.layers.Dropout(dropout_rate) if dropout_rate > 0 else None

    def call(self, inputs, training=False):
        x = inputs
        for layer in self.hidden_layers:
            x = layer(x)
            if self.dropout:
                x = self.dropout(x, training=training)
        return self.output_layer(x)

