optimizer = keras.optimizers.Adam(learning_rate=lr_schedule)

# Compile the model
model.compile(optimizer=optimizer, loss='mean_squared_error', metrics=['mae'])

# Train the model
history = model.fit(X_train, np.hstack((Y_real_train, Y_imag_train)), validation_data=(X_val, np.hstack((Y_real_val, Y_imag_val))), epochs=200, batch_size=32)

